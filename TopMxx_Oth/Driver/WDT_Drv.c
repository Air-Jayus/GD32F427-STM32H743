/****************************************************************************************************
函数名称：看门狗初始化
函数说明：
输入参数：
返 回 值：
其    它：
1、		独立看门狗（IWDG），LSI=32kHz，PSC=4→8kHz，重载80→超时10ms。
2、		配置顺序：使能LSI→解锁写访问→配PSC/RLR→启动IWDG。
****************************************************************************************************/
void WDT_Drv_Init(void)
{
	/* 使能LSI并等待就绪（IWDG时钟源） */
	LL_RCC_LSI_Enable();
	while(LL_RCC_LSI_IsReady() == 0) {}

	/* 解锁IWDG寄存器写访问（必须先写0x5555才能配PR/RLR） */
	LL_IWDG_EnableWriteAccess(IWDG1);

	/* 配置预分频器和重载值 */
	LL_IWDG_SetPrescaler(IWDG1, LL_IWDG_PRESCALER_4);
	LL_IWDG_SetReloadCounter(IWDG1, 80);

	/* 启动IWDG */
	LL_IWDG_Enable(IWDG1);
}
