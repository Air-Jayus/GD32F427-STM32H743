U16 Modbus_CRC16(U8 *AP,U8 Len)  //20220719加
{  
  U8 uchCRCHi=0xff;  
  U8 uchCRCLo=0xff;  
  U16  uindex;  
  while(Len--)  
  {  
		uindex=uchCRCHi^*AP++;  
		uchCRCHi=uchCRCLo^auchCRCHi[uindex];  
		uchCRCLo=auchCRCLo[uindex];  
  }  
  return (uchCRCHi<<8|uchCRCLo);  
} 

