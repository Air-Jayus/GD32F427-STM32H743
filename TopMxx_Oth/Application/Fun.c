/****************************************************************************************************
函数名称：CRC计算
函数说明：使用半字节查表法计算CRC_CCITT
输入参数：cData--新的计算数据	Crc--累计计算的结果
返 回 值：CRC计算结果
其    它：
****************************************************************************************************/
U16 Cal_CRC(U8 cData,U16 Crc)
{
	U8 cda;
	static U16 const Crc_Tab[16]={ /* CRC 余式表 */
		0x0000,0x1021,0x2042,0x3063,0x4084,0x50a5,0x60c6,0x70e7,
		0x8108,0x9129,0xa14a,0xb16b,0xc18c,0xd1ad,0xe1ce,0xf1ef};

	cData&=0x00ff;
	cda=((U8)(Crc>>8))>>4; 				/* 暂存CRC 的高四位 */
	Crc<<=4; 							/* CRC 右移4 位，相当于取CRC 的低12 位）*/
	Crc^=Crc_Tab[cda^(cData>>4)]; 		/* CRC 的高4 位和本字节的前半字节相加后查表计算CRC，然后加上上一次CRC 的余数 */
	cda=((U8)(Crc>>8))>>4;	 			/* 暂存CRC 的高4 位 */
	Crc<<=4; 							/* CRC 右移4 位， 相当于CRC 的低12 位） */
	Crc^=Crc_Tab[cda^(cData&0x0f)]; 	/* CRC 的高4 位和本字节的后半字节相加后查表计算CRC，然后再加上上一次CRC 的余数 */

	return(Crc);
}
/****************************************************************************************************
函数名称：U16数组CRC计算
函数说明：
输入参数：U16 *AP--数组指针，U16 Len--数组长度
返 回 值：CRC计算结果
其    它：
****************************************************************************************************/
U16 U16Array_Cal_CRC(U16 *AP,U16 Len)
{
	U16 Crc;
	U16 i;
	
	Crc=0;
	for(i=0;i<Len;i++)
	{
		Crc=Cal_CRC(AP[i]&0x00ff,Crc);
		Crc=Cal_CRC(AP[i]>>8,Crc);
	}
	return Crc;
}
